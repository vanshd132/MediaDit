/**
 * One-off asset fetcher: downloads latin-subset WOFF2 files for every typeface
 * the image-text editor can draw with, and emits the matching @font-face CSS.
 *
 *   node scripts/fetch-edit-fonts.mjs
 *
 * Self-hosting (rather than next/font or a Google Fonts <link>) keeps the tool
 * fully offline-capable, avoids any third-party request from a privacy tool,
 * and sidesteps the COEP: require-corp headers this site sets.
 */
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36";

const OUT_DIR = path.resolve("public/fonts");
const CSS_OUT = path.resolve("app/edit-fonts.css");

/** [googleFamilyName, hasItalic] */
const FAMILIES = [
  ["Arimo", true],
  ["Tinos", true],
  ["Cousine", true],
  ["Carlito", true],
  ["Caladea", true],
  ["Roboto", true],
  ["Open Sans", true],
  ["Lato", true],
  ["Source Sans 3", true],
  ["Noto Sans", true],
  ["Montserrat", true],
  ["Poppins", true],
  ["Raleway", true],
  ["Nunito", true],
  ["Oswald", false],
  ["Merriweather", true],
  ["Playfair Display", true],
  ["PT Serif", true],
  ["Lora", true],
  ["Roboto Mono", true],
];

const slug = (name) => name.toLowerCase().replace(/[^a-z0-9]+/g, "-");

const buildUrl = (family, hasItalic) => {
  const axis = hasItalic
    ? "ital,wght@0,400;0,700;1,400;1,700"
    : "wght@400;700";
  return `https://fonts.googleapis.com/css2?family=${encodeURIComponent(
    family
  )}:${axis}&display=block`;
};

/** Pull each @font-face block out of the Google CSS response. */
function parseFaces(css) {
  const faces = [];
  const re = /@font-face\s*\{([^}]*)\}/g;
  let m;
  while ((m = re.exec(css))) {
    const body = m[1];
    const get = (prop) => {
      const mm = new RegExp(`${prop}:\\s*([^;]+);`).exec(body);
      return mm ? mm[1].trim() : null;
    };
    const src = get("src");
    const urlMatch = src && /url\(([^)]+)\)\s*format\(['"]woff2['"]\)/.exec(src);
    if (!urlMatch) continue;
    faces.push({
      style: get("font-style") || "normal",
      weight: get("font-weight") || "400",
      unicodeRange: get("unicode-range") || "",
      url: urlMatch[1].replace(/['"]/g, ""),
    });
  }
  return faces;
}

/** The plain-latin block is the one that covers basic ASCII. */
const isLatin = (f) =>
  f.unicodeRange.includes("U+0000-00FF") || f.unicodeRange === "";

async function download(url, label) {
  const bin = await fetch(url, { headers: { "User-Agent": UA } });
  if (!bin.ok) {
    console.error(`! ${label}: font download failed (${bin.status})`);
    return null;
  }
  return Buffer.from(await bin.arrayBuffer());
}

async function main() {
  await mkdir(OUT_DIR, { recursive: true });
  const cssParts = [
    "/* Auto-generated by scripts/fetch-edit-fonts.mjs - do not edit by hand. */",
    "",
  ];
  let downloaded = 0;

  for (const [family, hasItalic] of FAMILIES) {
    const res = await fetch(buildUrl(family, hasItalic), {
      headers: { "User-Agent": UA },
    });
    if (!res.ok) {
      console.error(`! ${family}: css request failed (${res.status})`);
      continue;
    }
    const css = await res.text();
    const faces = parseFaces(css).filter(isLatin);

    // one face per (style, weight)
    const byStyle = new Map();
    for (const face of faces) {
      const key = `${face.style}-${face.weight}`;
      if (!byStyle.has(face.style)) byStyle.set(face.style, new Map());
      const weights = byStyle.get(face.style);
      if (!weights.has(key)) weights.set(face.weight, face.url);
    }

    for (const [style, weights] of byStyle) {
      const urls = [...new Set(weights.values())];

      // Google now ships most families as a single *variable* WOFF2 and returns
      // that same URL for every weight requested. Writing it out twice under a
      // static `font-weight: 700` rule does not produce bold — the browser just
      // instantiates the file's 400 default. Declaring the real axis range once
      // is what actually unlocks the heavier weights.
      if (urls.length === 1 && weights.size > 1) {
        const fileName = `${slug(family)}-variable-${style}.woff2`;
        const buf = await download(urls[0], `${family} ${style} variable`);
        if (!buf) continue;
        await writeFile(path.join(OUT_DIR, fileName), buf);
        downloaded++;
        cssParts.push(
          "@font-face {",
          `  font-family: "MD ${family}";`,
          `  font-style: ${style};`,
          "  font-weight: 400 700;",
          "  font-display: block;",
          `  src: url("/fonts/${fileName}") format("woff2");`,
          "}",
          ""
        );
        console.log(
          `  + ${family} ${style} variable 400-700 (${(buf.length / 1024).toFixed(1)}KB)`
        );
        continue;
      }

      for (const [weight, url] of weights) {
        const fileName = `${slug(family)}-${weight}-${style}.woff2`;
        const buf = await download(url, `${family} ${style} ${weight}`);
        if (!buf) continue;
        await writeFile(path.join(OUT_DIR, fileName), buf);
        downloaded++;
        cssParts.push(
          "@font-face {",
          `  font-family: "MD ${family}";`,
          `  font-style: ${style};`,
          `  font-weight: ${weight};`,
          "  font-display: block;",
          `  src: url("/fonts/${fileName}") format("woff2");`,
          "}",
          ""
        );
        console.log(
          `  + ${family} ${style} ${weight} (${(buf.length / 1024).toFixed(1)}KB)`
        );
      }
    }
  }

  await writeFile(CSS_OUT, cssParts.join("\n"), "utf8");
  console.log(`\nWrote ${downloaded} font files to public/fonts/`);
  console.log(`Wrote ${path.relative(process.cwd(), CSS_OUT)}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
