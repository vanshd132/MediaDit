/**
 * One-off asset fetcher: downloads latin-subset WOFF2 files for every typeface
 * the image-text editor can draw with, and emits the matching @font-face CSS
 * plus lib/editFonts.generated.ts (which variants really exist per family).
 *
 *   node scripts/fetch-edit-fonts.mjs
 *
 * Self-hosting (rather than next/font or a Google Fonts <link>) keeps the tool
 * fully offline-capable, avoids any third-party request from a privacy tool,
 * and sidesteps the COEP: require-corp headers this site sets.
 */
import { mkdir, writeFile, readdir, unlink } from "node:fs/promises";
import path from "node:path";
import { FONT_LIST } from "./edit-fonts.list.mjs";

const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36";

const OUT_DIR = path.resolve("public/fonts");
const CSS_OUT = path.resolve("app/edit-fonts.css");
const TS_OUT = path.resolve("lib/editFonts.generated.ts");

const slug = (name) => name.toLowerCase().replace(/[^a-z0-9]+/g, "-");

// Most specific first. Google silently omits styles/weights a family lacks
// (and 400s on some axis combos), so which variants really exist is read back
// from the faces it returns.
const SPECS = [
  "ital,wght@0,400;0,700;1,400;1,700",
  "wght@400;700",
  "ital@0;1",
  "",
];

const cssUrl = (family, axis) =>
  `https://fonts.googleapis.com/css2?family=${encodeURIComponent(family)}${
    axis ? ":" + axis : ""
  }&display=block`;

function parseFaces(css) {
  const faces = [];
  const re = /\/\*\s*([^*]+?)\s*\*\/\s*@font-face\s*\{([^}]*)\}/g;
  let m;
  while ((m = re.exec(css))) {
    const subset = m[1];
    const body = m[2];
    const get = (prop) => {
      const mm = new RegExp(`${prop}:\\s*([^;]+);`).exec(body);
      return mm ? mm[1].trim() : null;
    };
    const src = get("src");
    const urlMatch = src && /url\(([^)]+)\)\s*format\(['"]woff2['"]\)/.exec(src);
    if (!urlMatch) continue;
    faces.push({
      subset,
      style: get("font-style") || "normal",
      weight: get("font-weight") || "400",
      url: urlMatch[1].replace(/['"]/g, ""),
    });
  }
  return faces;
}

async function download(url, label) {
  const bin = await fetch(url, { headers: { "User-Agent": UA } });
  if (!bin.ok) {
    console.error(`! ${label}: font download failed (${bin.status})`);
    return null;
  }
  return Buffer.from(await bin.arrayBuffer());
}

async function fetchFamily(family) {
  for (const axis of SPECS) {
    const res = await fetch(cssUrl(family, axis), { headers: { "User-Agent": UA } });
    if (!res.ok) continue;
    const faces = parseFaces(await res.text()).filter((f) => f.subset === "latin");
    if (faces.length) return { faces };
  }
  return null;
}

async function main() {
  await mkdir(OUT_DIR, { recursive: true });
  for (const f of await readdir(OUT_DIR)) {
    if (f.endsWith(".woff2")) await unlink(path.join(OUT_DIR, f));
  }

  const cssParts = [
    "/* Auto-generated by scripts/fetch-edit-fonts.mjs - do not edit by hand. */",
    "",
  ];
  const table = [];
  let downloaded = 0;
  let bytes = 0;

  for (const [id, label, family, cls] of FONT_LIST) {
    const got = await fetchFamily(family);
    if (!got) {
      console.error(`! ${family}: not available, skipped`);
      continue;
    }

    const byStyle = new Map();
    for (const face of got.faces) {
      if (!byStyle.has(face.style)) byStyle.set(face.style, new Map());
      byStyle.get(face.style).set(face.weight, face.url);
    }

    for (const [style, weights] of byStyle) {
      const urls = [...new Set(weights.values())];
      // Google returns one *variable* file for every weight of most families.
      // A static `font-weight: 700` rule pointing at it does not give bold (the
      // browser instantiates the file's default), so declare the range once.
      const variable = urls.length === 1 && weights.size > 1;
      const entries = variable ? [["400 700", urls[0]]] : [...weights];
      for (const [weight, url] of entries) {
        const fileName = `${slug(family)}-${variable ? "variable" : weight}-${style}.woff2`;
        const buf = await download(url, `${family} ${style} ${weight}`);
        if (!buf) continue;
        await writeFile(path.join(OUT_DIR, fileName), buf);
        downloaded++;
        bytes += buf.length;
        cssParts.push(
          "@font-face {",
          `  font-family: "MD ${family}";`,
          `  font-style: ${style};`,
          `  font-weight: ${weight};`,
          "  font-display: block;",
          `  src: url("/fonts/${fileName}") format("woff2");`,
          "}",
          ""
        );
      }
    }

    table.push({
      id,
      label,
      family: `"MD ${family}"`,
      cls,
      hasItalic: got.faces.some((f) => f.style === "italic"),
      hasBold: got.faces.some((f) => f.style === "normal" && f.weight === "700"),
    });
    const t = table[table.length - 1];
    console.log(`  + ${family}${t.hasBold ? " [bold]" : ""}${t.hasItalic ? " [italic]" : ""}`);
  }

  await writeFile(CSS_OUT, cssParts.join("\n"), "utf8");
  await writeFile(
    TS_OUT,
    [
      "/* Auto-generated by scripts/fetch-edit-fonts.mjs - do not edit by hand. */",
      'import type { EditFont } from "./editFonts";',
      "",
      "export const GENERATED_FONTS: EditFont[] = " + JSON.stringify(table, null, 2) + ";",
      "",
    ].join("\n"),
    "utf8"
  );
  console.log(
    `\n${table.length} families, ${downloaded} files, ${(bytes / 1024 / 1024).toFixed(2)} MB`
  );
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
